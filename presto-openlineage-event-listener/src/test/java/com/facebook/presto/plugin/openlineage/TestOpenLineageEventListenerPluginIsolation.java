/**
 * Exercises the listener the way a Presto server does: the plugin and all of its
 * dependencies live in an isolated class loader whose only link to the outside world
 * is the SPI. SPI classes such as {@link QueryStatistics} come from a class loader that
 * cannot see any of the plugin's dependencies.
 * <p>
 * The other tests in this module run everything from one flat class path, which hides
 * class loading problems such as
 * <a href="https://github.com/prestodb/presto/issues/28460">prestodb/presto#28460</a>,
 * where a Jackson module found through {@code ServiceLoader} generated bytecode inside
 * the SPI class loader and failed with {@code NoClassDefFoundError} on a real server.
 */
public class TestOpenLineageEventListenerPluginIsolation
{
    // Keep in sync with PluginManagerUtil.SPI_PACKAGES in presto-main-base
    private static final List<String> SPI_PACKAGES = ImmutableList.of(
            "com.facebook.presto.spi.",
            "com.fasterxml.jackson.annotation.",
            "com.fasterxml.jackson.module.afterburner.",
            "io.airlift.slice.",
            "com.facebook.airlift.units.",
            "org.openjdk.jol.",
            "com.facebook.presto.common",
            "com.facebook.drift.annotations.",
            "com.facebook.drift.TException",
            "com.facebook.drift.TApplicationException");

    // One class per artifact that the server shares with plugins (the provided-scope dependencies of this module)
    private static final List<Class<?>> SPI_ARTIFACT_MARKERS = ImmutableList.of(
            QueryStatistics.class, // presto-spi
            RuntimeStats.class, // presto-common
            JsonProperty.class, // jackson-annotations
            Slice.class, // slice
            com.facebook.airlift.units.Duration.class, // units
            ClassLayout.class, // jol-core
            ThriftStruct.class); // drift-api

    @Test
    public void testCompletedEventWithIsolatedPluginClassLoader()
            throws Exception
    {
        Set<File> spiEntries = SPI_ARTIFACT_MARKERS.stream()
                .map(TestOpenLineageEventListenerPluginIsolation::codeSourceOf)
                .collect(toImmutableSet());
        List<URL> spiUrls = spiEntries.stream()
                .map(TestOpenLineageEventListenerPluginIsolation::toUrl)
                .collect(toImmutableList());
        List<URL> pluginUrls = testClassPath().stream()
                .filter(entry -> !spiEntries.contains(entry))
                .map(TestOpenLineageEventListenerPluginIsolation::toUrl)
                .collect(toImmutableList());

        try (URLClassLoader spiClassLoader = new URLClassLoader(spiUrls.toArray(new URL[0]), ClassLoader.getPlatformClassLoader());
                URLClassLoader pluginClassLoader = new IsolatedPluginClassLoader(pluginUrls, spiClassLoader)) {
            Class<?> runnerClass = pluginClassLoader.loadClass(CompletedEventRunner.class.getName());
            assertNotSame(runnerClass, CompletedEventRunner.class, "plugin classes must be loaded by the isolated class loader");
            Callable<?> runner = (Callable<?>) runnerClass.getConstructor().newInstance();

            // EventListenerManager creates the listener with the plugin class loader as context class loader
            Thread thread = Thread.currentThread();
            ClassLoader previousContextClassLoader = thread.getContextClassLoader();
            thread.setContextClassLoader(pluginClassLoader);
            @SuppressWarnings("unchecked")
            Map<String, String> queryStatistics;
            try {
                queryStatistics = (Map<String, String>) runner.call();
            }
            finally {
                thread.setContextClassLoader(previousContextClassLoader);
            }

            assertThat(queryStatistics)
                    .containsEntry("complete", "true")
                    .containsKeys("cpuTime", "wallTime", "peakUserMemoryBytes");
        }
    }

    /**
     * Runs inside the isolated plugin class loader; only JDK types cross the class loader boundary.
     */
    public static class CompletedEventRunner
            implements Callable<Map<String, String>>
    {
        @Override
        public Map<String, String> call()
        {
            ClassLoader pluginClassLoader = OpenLineageEventListener.class.getClassLoader();
            if (QueryStatistics.class.getClassLoader() == pluginClassLoader) {
                throw new IllegalStateException("SPI classes must not be loaded by the plugin class loader");
            }
            if (RunEvent.class.getClassLoader() != pluginClassLoader) {
                throw new IllegalStateException("Plugin dependencies must be loaded by the plugin class loader");
            }

            OpenLineageEventListener listener = (OpenLineageEventListener) new OpenLineageEventListenerFactory().create(Map.of(
                    "openlineage-event-listener.transport.type", "CONSOLE",
                    "openlineage-event-listener.presto.uri", "http://testhost"));

            RunEvent event = listener.getCompletedEvent(PrestoEventData.queryCompleteEvent);

            Map<String, String> queryStatistics = new HashMap<>();
            event.getRun().getFacets().getAdditionalProperties()
                    .get(OpenLineagePrestoFacet.PRESTO_QUERY_STATISTICS.asText())
                    .getAdditionalProperties()
                    .forEach((key, value) -> queryStatistics.put(key, String.valueOf(value)));
            return queryStatistics;
        }
    }

    /**
     * Same delegation rules as PluginClassLoader in presto-main-base: SPI packages come from the
     * SPI class loader, everything else must be found in the plugin's own jars, and the application
     * class loader is never consulted.
     */
    private static class IsolatedPluginClassLoader
            extends URLClassLoader
    {
        private final ClassLoader spiClassLoader;

        public IsolatedPluginClassLoader(List<URL> urls, ClassLoader spiClassLoader)
        {
            super(urls.toArray(new URL[0]), ClassLoader.getPlatformClassLoader());
            this.spiClassLoader = requireNonNull(spiClassLoader, "spiClassLoader is null");
        }

        @Override
        protected Class<?> loadClass(String name, boolean resolve)
                throws ClassNotFoundException
        {
            synchronized (getClassLoadingLock(name)) {
                Class<?> loadedClass = findLoadedClass(name);
                if (loadedClass == null && isSpiClass(name)) {
                    loadedClass = spiClassLoader.loadClass(name);
                }
                if (loadedClass == null) {
                    return super.loadClass(name, resolve);
                }
                if (resolve) {
                    resolveClass(loadedClass);
                }
                return loadedClass;
            }
        }

        @Override
        public URL getResource(String name)
        {
            if (isSpiResource(name)) {
                return spiClassLoader.getResource(name);
            }
            return super.getResource(name);
        }

        @Override
        public Enumeration<URL> getResources(String name)
                throws IOException
        {
            if (isSpiResource(name)) {
                return spiClassLoader.getResources(name);
            }
            return super.getResources(name);
        }

        private static boolean isSpiClass(String name)
        {
            return SPI_PACKAGES.stream().anyMatch(name::startsWith);
        }

        private static boolean isSpiResource(String name)
        {
            return SPI_PACKAGES.stream()
                    .map(spiPackage -> spiPackage.replace('.', '/'))
                    .anyMatch(name::startsWith);
        }
    }

    /**
     * The class path of this test JVM. Surefire boots the JVM with a single "manifest-only" jar
     * whose manifest lists the real class path, so manifest entries are expanded as well.
     */
    private static List<File> testClassPath()
            throws IOException
    {
        ImmutableList.Builder<File> entries = ImmutableList.builder();
        for (String entry : Splitter.on(File.pathSeparator).omitEmptyStrings().split(System.getProperty("java.class.path"))) {
            File file = new File(entry).getCanonicalFile();
            entries.add(file);
            if (file.isFile()) {
                entries.addAll(manifestClassPath(file));
            }
        }
        return entries.build();
    }

    private static List<File> manifestClassPath(File jar)
            throws IOException
    {
        try (JarFile jarFile = new JarFile(jar)) {
            Manifest manifest = jarFile.getManifest();
            String classPath = manifest == null ? null : manifest.getMainAttributes().getValue(Attributes.Name.CLASS_PATH);
            if (classPath == null) {
                return ImmutableList.of();
            }
            ImmutableList.Builder<File> entries = ImmutableList.builder();
            for (String item : Splitter.on(' ').omitEmptyStrings().split(classPath)) {
                entries.add(new File(jar.toURI().resolve(item)).getCanonicalFile());
            }
            return entries.build();
        }
    }

    private static File codeSourceOf(Class<?> clazz)
    {
        try {
            return new File(clazz.getProtectionDomain().getCodeSource().getLocation().toURI()).getCanonicalFile();
        }
        catch (IOException | URISyntaxException e) {
            throw new RuntimeException("Cannot locate code source of " + clazz.getName(), e);
        }
    }

    private static URL toUrl(File file)
    {
        try {
            return file.toURI().toURL();
        }
        catch (MalformedURLException e) {
            throw new RuntimeException(e);
        }
    }
}
